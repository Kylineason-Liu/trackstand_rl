#!/usr/bin/env bash
# Convert a .tflite file to a C++ header (hex array) for embedded firmware.
#
# Usage:
#   ./scripts/deployment/tflite_to_header.sh bicycle_policy_quantized.tflite
#
# Output:  bicycle_policy_quantized.h   (contains `const unsigned char model[]`)
#
set -euo pipefail

TFLITE="${1:?Usage: $0 <path/to/model.tflite>}"
NAME="$(basename "${TFLITE%.tflite}")"

echo "// Auto-generated by tflite_to_header.sh — DO NOT EDIT"  > "${NAME}.h"
echo "// Model: ${NAME}"                                        >> "${NAME}.h"
echo ""                                                         >> "${NAME}.h"
echo "#ifndef ${NAME^^}_H"                                      >> "${NAME}.h"
echo "#define ${NAME^^}_H"                                      >> "${NAME}.h"
echo ""                                                         >> "${NAME}.h"
echo "#include <cstdint>"                                       >> "${NAME}.h"
echo ""                                                         >> "${NAME}.h"
echo "alignas(16) const unsigned char ${NAME}[] = {"            >> "${NAME}.h"

xxd -i < "${TFLITE}" | tail -n +2 | head -n -1                  >> "${NAME}.h"

echo "};"                                                       >> "${NAME}.h"
echo "const unsigned int ${NAME}_len = sizeof(${NAME});"        >> "${NAME}.h"
echo ""                                                         >> "${NAME}.h"
echo "#endif  // ${NAME^^}_H"                                   >> "${NAME}.h"

echo "[INFO] Header written to: ${NAME}.h"
echo "[INFO] Array size: $(wc -c < "${TFLITE}") bytes"
